#!/usr/bin/env node
/**
 * Flatten one Edge Function and its ../_shared/* imports into a single file.
 *
 *   node migration-package/scripts/bundle-function.mjs sms-reports
 *
 * WHY
 * The Supabase dashboard's function editor is the only way to deploy without
 * a terminal, and pasting four files in the right order is a step where
 * something goes wrong quietly. One file cannot be pasted half-right.
 *
 * Remote imports (https://…) are left exactly as they are — Deno fetches
 * them at runtime and the dashboard expects that. Only the local
 * ../_shared/*.js imports are inlined, with their `export` keywords stripped
 * so the result is one module.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'

const fn = process.argv[2]
if (!fn) { console.error('usage: bundle-function.mjs <function-name>'); process.exit(2) }
const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '..', '..')
const SRC = join(ROOT, 'supabase/functions', fn, 'index.ts')

let src
try { src = readFileSync(SRC, 'utf8') } catch { console.error(`no such function: ${fn}`); process.exit(2) }

const shared = []
const seen = new Set()
// import { a, b } from '../_shared/x.js'
const localImport = /^import\s*\{([^}]+)\}\s*from\s*['"]\.\.\/_shared\/([A-Za-z0-9_.-]+)['"]\s*;?\s*$/gm

let m
while ((m = localImport.exec(src)) !== null) {
  const file = m[2]
  if (seen.has(file)) continue
  seen.add(file)
  const names = m[1].split(',').map(x => x.trim().split(/\s+as\s+/).pop()).filter(Boolean)
  const text = readFileSync(join(ROOT, 'supabase/functions/_shared', file), 'utf8')
  shared.push({ file, text, names })
}

// Strip the local imports; keep every remote one untouched.
let body = src.replace(localImport, (line) => `// inlined below: ${line.trim()}`)

/**
 * Each inlined module goes inside its own function scope, and only the names
 * that were imported come out.
 *
 * Concatenating the bodies instead produced
 *     Uncaught SyntaxError: Identifier 'fmt' has already been declared
 * because _shared/reports.js and sms-reports/index.ts both define a `fmt`
 * helper. `deno check` passed that file; only running it found the collision,
 * which is the second time checking was not evidence.
 *
 * Scoping also means a shared module can define whatever private helpers it
 * likes without colliding with any host file, now or later.
 */
const scoped = (file, text, names) => {
  // These modules are deliberately import-free so Deno and Node can both load
  // them; a nested import would not be legal inside a function body.
  const hasImport = /^\s*import\s/m.test(text)
  if (hasImport) {
    throw new Error(`_shared/${file} has an import; it cannot be scoped. Keep the shared modules import-free.`)
  }
  const body = text
    .replace(/^export\s+(async\s+)?function\s/gm, (s_, a) => `${a || ''}function `)
    .replace(/^export\s+(const|let|var)\s/gm, '$1 ')
    .replace(/^export\s+default\s/gm, 'const __default = ')
    .replace(/^export\s*\{[^}]*\}\s*;?\s*$/gm, '')
  return `const { ${names.join(', ')} } = (() => {\n` +
         body.trimEnd().split('\n').map(l => l ? '  ' + l : '').join('\n') +
         `\n  return { ${names.join(', ')} }\n})()\n`
}

const header = `// ===========================================================================
// ${fn} — a single file, for the Supabase dashboard's function editor.
//
// Generated by migration-package/scripts/bundle-function.mjs. Do not edit
// this copy: edit supabase/functions/${fn}/index.ts and the modules under
// supabase/functions/_shared/, then regenerate.
//
// Inlined: ${shared.length ? shared.map(s => '_shared/' + s.file).join(', ') : 'nothing'}
// Remote imports (https://…) are left as they are; Deno fetches them.
//
// Generated ${new Date().toISOString().slice(0, 19)}Z
// ===========================================================================

`

const parts = [header]
for (const s of shared) {
  parts.push(`// ───────── _shared/${s.file} — scoped, exporting: ${s.names.join(', ')} ─────────\n`)
  parts.push(scoped(s.file, s.text, s.names) + '\n')
}
parts.push(`// ───────── ${fn}/index.ts ─────────\n`)
parts.push(body.trimEnd() + '\n')

const out = parts.join('')
const dir = join(ROOT, 'release/paste-ready')
mkdirSync(dir, { recursive: true })
const dest = join(dir, `${fn}.ts`)
writeFileSync(dest, out)

// A function that still has a local import would fail at runtime.
const leftover = /from\s*['"]\.\.?\//.test(out.replace(/^\/\/.*$/gm, ''))
console.log(`${fn}: ${out.split('\n').length} lines -> release/paste-ready/${fn}.ts`)
console.log(`  inlined   : ${shared.length ? shared.map(s => s.file).join(', ') : 'none'}`)
console.log(`  remote     : ${(out.match(/from\s*['"]https:\/\/[^'"]+['"]/g) || []).length} import(s), untouched`)
console.log(`  local left : ${leftover ? 'YES — BROKEN' : 'none'}`)
if (leftover) process.exit(1)
